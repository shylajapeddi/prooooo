def parse_boolean_expression(expression):
    """Parse a small, explicit Boolean-expression grammar for variables A-F."""
    expression = (expression or "").strip()
    if not expression:
        raise ValueError("Enter a Boolean expression first.")

    if not re.fullmatch(r"[A-Fa-f01\s&|~()]+", expression):
        raise ValueError(
            "Use only variables A-F, constants 0/1, operators &, |, ~, and parentheses."
        )

    normalized = expression.upper()
    tokens = re.findall(r"[A-F01&|~()]", normalized)
    if not tokens:
        raise ValueError("Enter a Boolean expression first.")

    position = 0

    def parse_atom():
        nonlocal position
        if position >= len(tokens):
            raise ValueError("Expression ends unexpectedly. Check your parentheses and operators.")

        token = tokens[position]
        if token == "~":
            position += 1
            return sp.Not(parse_atom(), evaluate=False)
        if token == "(":
            position += 1
            value = parse_or()
            if position >= len(tokens) or tokens[position] != ")":
                raise ValueError("A closing parenthesis ')' is missing.")
            position += 1
            return value
        if token == ")" or token in ("&", "|"):
            raise ValueError(f"Unexpected operator or parenthesis: {token}")

        position += 1
        if token == "0":
            return sp.false
        if token == "1":
            return sp.true
        if token in VARIABLE_NAMES:
            return sp.Symbol(token)
        raise ValueError(f"Unsupported token: {token}")

    def parse_and():
        nonlocal position
        values = [parse_atom()]
        while position < len(tokens) and tokens[position] == "&":
            position += 1
            values.append(parse_atom())
        return values[0] if len(values) == 1 else sp.And(*values, evaluate=False)

    def parse_or():
        nonlocal position
        values = [parse_and()]
        while position < len(tokens) and tokens[position] == "|":
            position += 1
            values.append(parse_and())
        return values[0] if len(values) == 1 else sp.Or(*values, evaluate=False)

    original = parse_or()
    if position != len(tokens):
        token = tokens[position]
        if token == ")":
            raise ValueError("There is an extra closing parenthesis ')'.")
        raise ValueError(f"Unexpected token '{token}'. Add an operator between terms.")

    # Use the tokens rather than free_symbols so variables remain listed even
    # when the expression contains a constant such as A & 0.
    names = sorted({token for token in tokens if token in VARIABLE_NAMES})
    return normalized, original, names


def bool_value(expr, assignment):
    value = expr.subs(assignment)
    return int(bool(value))


def make_truth_table(original, simplified, variables):
    rows = []
    for bits in product([0, 1], repeat=len(variables)):
        assignment = {
            sp.Symbol(variable): bool(bit)
            for variable, bit in zip(variables, bits)
        }
        original_value = bool_value(original, assignment)
        optimized_value = bool_value(simplified, assignment)
        row = {variable: bit for variable, bit in zip(variables, bits)}
        row.update({"Original F": original_value, "Optimized F": optimized_value})
        rows.append(row)
    return pd.DataFrame(rows)


def verilog_expr(expr):
    if expr == sp.true:
        return "1'b1"
    if expr == sp.false:
        return "1'b0"
    if isinstance(expr, sp.Symbol):
        return str(expr)
    if isinstance(expr, sp.Not):
        return f"~({verilog_expr(expr.args[0])})"
    if isinstance(expr, sp.And):
        return "(" + " & ".join(verilog_expr(arg) for arg in expr.args) + ")"
    if isinstance(expr, sp.Or):
        return "(" + " | ".join(verilog_expr(arg) for arg in expr.args) + ")"
    raise ValueError(f"Unsupported Boolean expression node: {expr}")


def make_verilog(original, simplified, variables):
    ports = ", ".join(variables + ["F"])
    input_declaration = f"    input {', '.join(variables)};\n" if variables else ""

    return (
        "// Generated by Boolean Expression Optimizer & Circuit Simulator Pro\n"
        f"module original_circuit({ports});\n"
        f"{input_declaration}"
        "    output F;\n"
        f"    assign F = {verilog_expr(original)};\n"
        "endmodule\n\n"
        f"module optimized_circuit({ports});\n"
        f"{input_declaration}"
        "    output F;\n"
        f"    assign F = {verilog_expr(simplified)};\n"
        "endmodule\n"
    )


